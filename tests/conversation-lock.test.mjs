import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { ConversationLocks } = require('../lib/conversation-lock.js');
const locks = new ConversationLocks({ maxQueued: 2, timeoutMs: 1000 });
const release = await locks.acquire('tenant:conversation');
let entered = false;
const pending = locks.acquire('tenant:conversation').then((unlock) => { entered = true; return unlock; });
await Promise.resolve();
assert.equal(entered, false, 'same conversation waits for the preceding turn commit');
const otherRelease = await locks.acquire('tenant:other');
otherRelease();
release();
const releaseNext = await pending;
assert.equal(entered, true);
releaseNext();
releaseNext();
assert.equal(locks.size, 0, 'idle locks leave no retained session keys');
const first = await locks.acquire('cancel');
const controller = new AbortController();
const canceled = locks.acquire('cancel', { signal: controller.signal });
const afterCanceled = locks.acquire('cancel');
controller.abort();
await assert.rejects(canceled, (err) => err.code === 'REQUEST-ABORTED');
first();
(await afterCanceled)();
assert.equal(locks.size, 0, 'canceled waiter cannot retain or steal a lock');
const hold = await locks.acquire('bounded');
const q1 = locks.acquire('bounded');
const q2 = locks.acquire('bounded');
await assert.rejects(locks.acquire('bounded'), (err) => err.code === 'QUEUE_FULL');
hold();
(await q1)();
(await q2)();
const closing = await locks.acquire('close');
const queued = locks.acquire('close');
locks.close();
await assert.rejects(queued, (err) => err.code === 'SERVER-SHUTDOWN');
closing();
assert.equal(locks.size, 0);
console.log('conversation lock tests: all passed');
